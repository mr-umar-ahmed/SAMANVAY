/* ── Photo capture (compressed, stored in IndexedDB) ────────── */
async function compressImage(file: File, maxPx = 1280, quality = 0.7): Promise<{ full: Blob; thumb: string }> {
  const bitmap = await createImageBitmap(file);
  const scale = Math.min(1, maxPx / Math.max(bitmap.width, bitmap.height));
  const canvas = document.createElement('canvas');
  canvas.width = Math.round(bitmap.width * scale);
  canvas.height = Math.round(bitmap.height * scale);
  const ctx = canvas.getContext('2d')!;
  ctx.drawImage(bitmap, 0, 0, canvas.width, canvas.height);
  const full: Blob = await new Promise((res) => canvas.toBlob((b) => res(b!), 'image/jpeg', quality));
  const tScale = Math.min(1, 240 / Math.max(canvas.width, canvas.height));
  const tc = document.createElement('canvas');
  tc.width = Math.round(canvas.width * tScale);
  tc.height = Math.round(canvas.height * tScale);
  tc.getContext('2d')!.drawImage(canvas, 0, 0, tc.width, tc.height);
  return { full, thumb: tc.toDataURL('image/jpeg', 0.6) };
}

export async function loadPhoto(photoId: string): Promise<string | null> {
  const blob = await idbGet<Blob>(`photo:${photoId}`);
  return blob ? URL.createObjectURL(blob) : null;
}

export async function deletePhoto(photoId: string) {
  await idbDel(`photo:${photoId}`);
}

export function PhotoCapture({ value, onChange, label = 'Take or choose a photo' }: { value: { photoId: string; thumb: string } | null; onChange: (v: { photoId: string; thumb: string } | null) => void; label?: string }) {
  const ref = useRef<HTMLInputElement>(null);
  const [busy, setBusy] = useState(false);
  const pick = async (file: File | undefined) => {
    if (!file) return;
    setBusy(true);
    try {
      const { full, thumb } = await compressImage(file);
      const photoId = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 7)}`;
      await idbSet(`photo:${photoId}`, full);
      onChange({ photoId, thumb });
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className="stack">
      <input ref={ref} type="file" accept="image/*" capture="environment" hidden onChange={(e) => void pick(e.target.files?.[0])} />
      {value ? (
        <div className="row" style={{ alignItems: 'flex-start' }}>
          <img src={value.thumb} alt="Captured" style={{ width: 120, height: 120, objectFit: 'cover', borderRadius: 8, border: '1px solid var(--line)' }} />
          <div className="stack">
            <button type="button" className="btn btn-sm" onClick={() => ref.current?.click()}>
              <Camera /> Retake
            </button>
            <button type="button" className="btn btn-sm btn-ghost" onClick={() => { void deletePhoto(value.photoId); onChange(null); }}>
              <Trash2 /> Remove
            </button>
          </div>
        </div>
      ) : (
        <button type="button" className="btn btn-lg" style={{ borderStyle: 'dashed', minHeight: 96, justifyContent: 'center' }} onClick={() => ref.current?.click()} disabled={busy}>
          <Camera /> {busy ? 'Compressing…' : label}
        </button>
      )}
      <div className="tiny muted">Photos are compressed to 1280 px and stored on this device only.</div>
    </div>
  );
}

/* ── Location picker (GPS → nearest chainage) ───────────────── */
export interface LocationValue {
  lat?: number;
  lng?: number;
  accuracyM?: number;
  km?: number;
  line?: Line;
  station?: string;
  sectionLabel?: string;
  distanceM?: number;
}

export function LocationPicker({ corridor, value, onChange, labels }: { corridor: Corridor; value: LocationValue; onChange: (v: LocationValue) => void; labels?: { use: string; locating: string; found: string; denied: string; station: string; km: string } }) {
  const L = labels ?? { use: 'Use my location', locating: 'Finding your location…', found: 'Location captured', denied: 'Location not available — pick the nearest station below.', station: 'Nearest station', km: 'Chainage (km)' };
  const [state, setState] = useState<'idle' | 'locating' | 'ok' | 'denied'>(value.lat ? 'ok' : 'idle');
  const locate = () => {
    if (!navigator.geolocation) return setState('denied');
    setState('locating');
    navigator.geolocation.getCurrentPosition(
      (pos) => {
        const s: Snapped = snapToCorridor(corridor, pos.coords.latitude, pos.coords.longitude);
        onChange({ ...value, lat: pos.coords.latitude, lng: pos.coords.longitude, accuracyM: Math.round(pos.coords.accuracy), km: s.km, station: s.station, sectionLabel: s.sectionLabel, distanceM: s.distanceM });
        setState('ok');
      },
      () => setState('denied'),
      { enableHighAccuracy: true, timeout: 12000, maximumAge: 30000 }
    );
  };
  const setStation = (code: string) => {
    const st = corridor.stations.find((s) => s.code === code);
    if (!st) return;
    onChange({ ...value, station: st.code, km: st.km, sectionLabel: undefined, lat: st.lat, lng: st.lng, distanceM: undefined });
  };
  return (
    <div className="stack">
      <div className="row-wrap">
        <button type="button" className="btn" onClick={locate} disabled={state === 'locating'}>
          <Crosshair className={state === 'locating' ? 'spin' : ''} /> {state === 'locating' ? L.locating : L.use}
        </button>
        {state === 'ok' && value.km !== undefined && (
          <span className="badge badge-ok">
            {L.found} · km {value.km.toFixed(1)} · {value.station}
            {value.distanceM !== undefined ? ` · ${value.distanceM >= 1000 ? `${(value.distanceM / 1000).toFixed(1)} km` : `${value.distanceM} m`} from line` : ''}
            {value.accuracyM ? ` · ±${value.accuracyM} m` : ''}
          </span>
        )}
        {state === 'denied' && <span className="badge badge-warn">{L.denied}</span>}
      </div>
      <div className="form-grid">
        <div className="field">
          <label>{L.station}</label>
          <select className="select" value={value.station ?? ''} onChange={(e) => setStation(e.target.value)}>
            <option value="">—</option>
            {corridor.stations.map((s) => (
              <option key={s.code} value={s.code}>{s.code} · {s.name} (km {s.km})</option>
            ))}
          </select>
        </div>
        <div className="field">
          <label>{L.km}</label>
          <input className="input" type="number" min={0} max={corridor.lengthKm} step={0.1} value={value.km ?? ''} onChange={(e) => onChange({ ...value, km: e.target.value === '' ? undefined : Number(e.target.value) })} />
        </div>
      </div>
    </div>
  );
}
