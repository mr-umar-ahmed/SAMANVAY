/* ── Audit trail / timeline ─────────────────────────────────── */
export function AuditTrail({ entries, limit = 12 }: { entries: AuditEntry[]; limit?: number }) {
  if (!entries.length) return <div className="empty">No actions recorded yet.</div>;
  return (
    <ul className="timeline">
      {entries.slice(0, limit).map((e) => (
        <li key={e.id} className={e.action.includes('REFUSED') || e.action.includes('OBJECTION') ? 'crit' : e.action.includes('GRANTED') || e.action.includes('CONCUR') || e.action.includes('CLEARED') ? 'ok' : ''}>
          <div className="row" style={{ gap: 6 }}>
            <b className="small">{e.action.replace(/_/g, ' ').toLowerCase().replace(/^\w/, (c) => c.toUpperCase())}</b>
            <span className="when right">{timeAgo(e.at)}</span>
          </div>
          <div className="tiny muted">
            {e.by} · {e.role.replace(/_/g, ' ').toLowerCase()}
            {e.detail ? ` · ${e.detail}` : ''}
          </div>
        </li>
      ))}
    </ul>
  );
}

export function Timeline({ steps }: { steps: { label: ReactNode; when?: string; state: 'done' | 'current' | 'pending'; note?: ReactNode }[] }) {
  return (
    <ul className="timeline">
      {steps.map((s, i) => (
        <li key={i} className={s.state === 'done' ? 'ok' : s.state === 'current' ? 'warn' : ''} style={{ opacity: s.state === 'pending' ? 0.6 : 1 }}>
          <div className="row" style={{ gap: 6 }}>
            <b className="small">{s.label}</b>
            {s.when && <span className="when right">{s.when}</span>}
          </div>
          {s.note && <div className="tiny muted">{s.note}</div>}
        </li>
      ))}
    </ul>
  );
}

/* ── Time scrubber (simulated clock) ────────────────────────── */
export function TimeScrubber({ minute, onChange, playing, onPlay, speed = 60, dayLabel, onNow }: { minute: number; onChange: (m: number) => void; playing: boolean; onPlay: (p: boolean) => void; speed?: number; dayLabel?: string; onNow?: () => void }) {
  useEffect(() => {
    if (!playing) return;
    const id = setInterval(() => onChange((minute + Math.max(1, Math.round(speed / 60))) % 1440), 1000);
    return () => clearInterval(id);
  }, [playing, minute, speed, onChange]);
  return (
    <div className="row" style={{ gap: 10, flexWrap: 'wrap' }} data-tour="time-scrubber">
      <button className="btn btn-sm btn-icon" onClick={() => onPlay(!playing)} aria-label={playing ? 'Pause' : 'Play'}>
        {playing ? <Pause /> : <Play />}
      </button>
      <span className="mono strong num" style={{ minWidth: 48 }}>{hhmm(minute)}</span>
      <input type="range" min={0} max={1439} value={minute} onChange={(e) => onChange(Number(e.target.value))} style={{ flex: 1, minWidth: 160 }} aria-label="Minute of day" />
      {dayLabel && <span className="small muted">{dayLabel}</span>}
      {onNow && (
        <button className="btn btn-sm" onClick={onNow}>Now</button>
      )}
      <SimLabel kind="simClock" short />
    </div>
  );
}

/* ── Chip group / slider ────────────────────────────────────── */
export function ChipGroup<T extends string>({ options, value, onChange, multi }: { options: { value: T; label: ReactNode; icon?: ReactNode }[]; value: T | T[]; onChange: (v: T | T[]) => void; multi?: boolean }) {
  const selected = Array.isArray(value) ? value : [value];
  return (
    <div className="row-wrap" role="group">
      {options.map((o) => {
        const on = selected.includes(o.value);
        return (
          <button
            key={o.value}
            type="button"
            className={`btn btn-sm ${on ? 'btn-dark' : ''}`}
            aria-pressed={on}
            onClick={() => {
              if (!multi) return onChange(o.value);
              onChange(on ? (selected.filter((v) => v !== o.value) as T[]) : ([...selected, o.value] as T[]));
            }}
          >
            {o.icon}
            {o.label}
          </button>
        );
      })}
    </div>
  );
}

export function Slider({ label, value, min, max, step = 1, onChange, format, hint }: { label: ReactNode; value: number; min: number; max: number; step?: number; onChange: (v: number) => void; format?: (v: number) => string; hint?: ReactNode }) {
  return (
    <div className="field">
      <div className="row">
        <label className="grow">{label}</label>
        <span className="mono strong num">{format ? format(value) : value}</span>
      </div>
      <input type="range" min={min} max={max} step={step} value={value} onChange={(e) => onChange(Number(e.target.value))} />
      {hint && <div className="hint">{hint}</div>}
    </div>
  );
}

