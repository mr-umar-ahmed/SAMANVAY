/* ── Honesty labels (fixed wording, see docs/v4-spec.md §8) ─── */
export type SimKind = 'seededFeed' | 'seededRecords' | 'wttPositions' | 'simClock' | 'baseline' | 'model' | 'solver' | 'assumption' | 'planningEstimate' | 'localAuth' | 'localOnly' | 'notOfficial';

const SIM_TEXT: Record<SimKind, { label: string; text: (system?: string, seed?: number | string, source?: string) => string }> = {
  seededFeed: { label: 'Simulated feed', text: (sys, seed) => `Simulated feed — seeded ${sys ?? 'source'}-shaped data${seed !== undefined ? `, seed ${seed}` : ''}. No live link.` },
  seededRecords: { label: 'Seeded history', text: () => 'Records before today are seeded history; records made on this device are real app state.' },
  wttPositions: { label: 'Derived from timetable', text: () => 'Train positions derived from the working timetable, not GPS or NTES.' },
  simClock: { label: 'Simulated clock', text: () => 'Simulated clock (scrubber), not wall time.' },
  baseline: { label: 'Simulated baseline', text: () => 'Baseline: simulated decentralised FIFO practice, same seed, computed like-for-like.' },
  model: { label: 'Fitted model', text: () => 'Model fitted on seeded history; metrics on a held-out split.' },
  solver: { label: 'In-browser solver', text: () => 'In-browser solver: greedy construction + simulated annealing. CP-SAT reference formulation documented, not executed.' },
  assumption: { label: 'Assumption', text: (_s, _seed, source) => `Assumption — editable. Source: ${source ?? 'planning cell estimate'}.` },
  planningEstimate: { label: 'Planning estimate', text: () => 'Planning estimate from the block programme, not live running.' },
  localAuth: { label: 'Browser-local accounts', text: () => 'Browser-local demo accounts — no server, no real authentication.' },
  localOnly: { label: 'Stored on this device', text: () => 'Stored in this browser only — nothing is transmitted.' },
  notOfficial: { label: 'Not an official document', text: () => 'Generated by SAMANVAY — not an official document until signed.' },
};

export function SimLabel({ kind, system, seed, source, short }: { kind: SimKind; system?: string; seed?: number | string; source?: string; short?: boolean }) {
  const t = SIM_TEXT[kind];
  const cls = kind === 'assumption' ? 'tag-assumption' : 'tag-sim';
  return (
    <span className={cls} title={t.text(system, seed, source)}>
      {kind === 'assumption' ? <ShieldCheck size={10} /> : <FlaskConical size={10} />}
      {short ? t.label.split(' ')[0] : t.label}
    </span>
  );
}

